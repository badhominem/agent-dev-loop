"""`loop install`: put the loop into a repo and generate each harness's files from loop/.

Never overwrites a file a person wrote. Generated harness files carry a header
saying where they come from, and are rewritten on every install.
"""

from __future__ import annotations

import json
import re
import shutil
from abc import ABC, abstractmethod
from pathlib import Path

from devloop.config import ROLES, ToolRegistry, as_dict, as_list

TEMPLATES = Path(__file__).parent / "templates"
GENERATED = "<!-- Generated by `loop install` from loop/agents/{role}.md or the devloop defaults. -->"
GUARD_COMMAND = "loop guard"
POINTER = (
    "\n## Agent Dev Loop\n\nRead `loop/principles.md` first. "
    "Your role, if `loop` started you, is in `.loop/session.yaml`.\n"
)


def agent_text(repo: Path, role: str) -> str:
    """A repo's own loop/agents/<role>.md wins over the packaged default."""
    custom = repo / "loop" / "agents" / f"{role}.md"
    return (custom if custom.exists() else TEMPLATES / "agents" / f"{role}.md").read_text(encoding="utf-8")


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not match:
        return {}, text
    meta = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip()
    return meta, match.group(2)


class Adapter(ABC):
    name: str

    @abstractmethod
    def install(self, repo: Path) -> list[str]: ...


class ClaudeCodeAdapter(Adapter):
    name = "claude"

    def install(self, repo: Path) -> list[str]:
        written = []
        agents = repo / ".claude" / "agents"
        agents.mkdir(parents=True, exist_ok=True)
        for role in ROLES:
            meta, body = split_frontmatter(agent_text(repo, role))
            head = f"---\nname: loop-{role}\ndescription: {json.dumps(meta.get('description', role))}\n---\n"
            (agents / f"loop-{role}.md").write_text(head + GENERATED.format(role=role) + "\n" + body, encoding="utf-8")
            written.append(f".claude/agents/loop-{role}.md")
        path = repo / ".claude" / "settings.json"
        settings = as_dict(json.loads(path.read_text(encoding="utf-8"))) if path.exists() else {}
        hooks = as_dict(settings.get("hooks"))
        pre = [h for h in as_list(hooks.get("PreToolUse")) if isinstance(h, dict)]
        if not any(GUARD_COMMAND in json.dumps(h) for h in pre):
            pre.append({"matcher": "", "hooks": [{"type": "command", "command": GUARD_COMMAND}]})
        hooks["PreToolUse"] = pre
        settings["hooks"] = hooks
        permissions = as_dict(settings.get("permissions"))
        registry = ToolRegistry.load(repo)
        for key, attr in (("allow", "allow"), ("ask", "ask"), ("deny", "deny")):
            current = [str(x) for x in as_list(permissions.get(key))]
            for tool in registry.tools:
                for prefix in getattr(tool, attr):
                    for rule in (f"Bash({prefix})", f"Bash({prefix} *)"):
                        if rule not in current:
                            current.append(rule)
            permissions[key] = current
        settings["permissions"] = permissions
        path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
        written.append(".claude/settings.json (guard hook and tool permissions)")
        return written


class CopilotAdapter(Adapter):
    name = "copilot"

    def install(self, repo: Path) -> list[str]:
        written = []
        agents = repo / ".github" / "agents"
        agents.mkdir(parents=True, exist_ok=True)
        for role in ROLES:
            meta, body = split_frontmatter(agent_text(repo, role))
            head = f"---\nname: loop-{role}\ndescription: {json.dumps(meta.get('description', role))}\n---\n"
            (agents / f"loop-{role}.agent.md").write_text(
                head + GENERATED.format(role=role) + "\n" + body, encoding="utf-8"
            )
            written.append(f".github/agents/loop-{role}.agent.md")
        hooks = repo / ".github" / "hooks"
        hooks.mkdir(parents=True, exist_ok=True)
        config = {
            "version": 1,
            "hooks": {
                "preToolUse": [
                    {"type": "command", "bash": GUARD_COMMAND, "powershell": GUARD_COMMAND, "timeoutSec": 30}
                ]
            },
        }
        (hooks / "loop-guard.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        written.append(".github/hooks/loop-guard.json")
        return written


ADAPTERS: dict[str, Adapter] = {a.name: a for a in (ClaudeCodeAdapter(), CopilotAdapter())}


def install(repo: Path, harnesses: list[str]) -> list[str]:
    written: list[str] = []
    skeleton = TEMPLATES / "skeleton"
    for source in sorted(p for p in skeleton.rglob("*") if p.is_file()):
        target = repo / source.relative_to(skeleton)
        if target.name == "AGENTS.md" and target.exists():
            text = target.read_text(encoding="utf-8")
            if "loop/principles.md" not in text:
                target.write_text(text.rstrip() + "\n" + POINTER, encoding="utf-8")
                written.append("AGENTS.md (added a pointer)")
            continue
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            written.append(str(target.relative_to(repo)))
    for folder in ("components", "behaviour", "demands", "agents"):
        (repo / "loop" / folder).mkdir(parents=True, exist_ok=True)
        keep = repo / "loop" / folder / ".gitkeep"
        if not any((repo / "loop" / folder).iterdir()):
            keep.write_text("", encoding="utf-8")
    ignore = repo / ".gitignore"
    lines = ignore.read_text(encoding="utf-8").splitlines() if ignore.exists() else []
    if ".loop/" not in lines:
        ignore.write_text("\n".join([*lines, ".loop/"]) + "\n", encoding="utf-8")
        written.append(".gitignore (.loop/)")
    for name in harnesses:
        if name not in ADAPTERS:
            raise SystemExit(f"Unknown harness '{name}'. Choose from: {', '.join(ADAPTERS)}.")
        written += ADAPTERS[name].install(repo)
    return written
